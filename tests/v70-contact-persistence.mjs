import { readFileSync } from "node:fs";
import { JSDOM } from "jsdom";
import assert from "node:assert/strict";
const dom=new JSDOM('<!doctype html><body><form id="f"><input id="tparty" value="New Customer"><input id="txnPartyPhone" value="+919876543210"></form></body>',{url:"https://smartledger.test/",runScripts:"dangerously"});
const w=dom.window;
const data={sales:[],purchases:[],customers:[],suppliers:[]};
w.get=key=>data[key]||[];
w.put=(key,value)=>{data[key]=value;};
w.saveTransaction=function(event,kind){event.preventDefault();const party=w.document.querySelector("#tparty").value;const master=kind==="sales"?"customers":"suppliers";if(kind==="sales"&&!w.get(master).some(x=>x.name===party))w.get(master).push({name:party,phone:"",address:"",opening:0});const rows=w.get(kind);rows.push({id:101,party,invoice:"SL-101"});w.put(kind,rows);};
w.eval(readFileSync("smartledger-workflow-v70.js","utf8"));
assert.equal(w.smartLedgerV70Ready,true,"v70 enhancement initializes");
w.saveTransaction(new w.Event("submit",{cancelable:true}),"sales");
assert.equal(data.sales[0].partyPhone,"+919876543210","Phone is persisted on the saved transaction");
assert.equal(data.customers[0].phone,"+919876543210","Phone is persisted on the customer master");
assert.deepEqual(w.smartLedgerV70LastSaved,{kind:"sales",id:101,party:"New Customer",phone:"+919876543210"});
w.get("suppliers").push({name:"Existing Supplier",phone:""});
w.document.querySelector("#tparty").value="Existing Supplier";
w.document.querySelector("#txnPartyPhone").value="+919812345678";
w.saveTransaction(new w.Event("submit",{cancelable:true}),"purchases");
assert.equal(data.purchases[0].partyPhone,"+919812345678","Supplier phone is persisted on the purchase");
assert.equal(data.suppliers[0].phone,"+919812345678","Supplier master phone is updated");
console.log("PASS v70 sales transaction phone persistence");
console.log("PASS v70 new customer master phone persistence");
console.log("PASS v70 purchase transaction and supplier master phone persistence");
dom.window.close();