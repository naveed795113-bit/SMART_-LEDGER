import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { JSDOM, VirtualConsole } from "jsdom";

const html=readFileSync("index.html","utf8")
 .replace(/<script src="[^"]+"><\/script>/g,"")
 .replace(/<script src='[^']+'><\/script>/g,"");
const source=readFileSync("units-conversions-v1.js","utf8");
const errors=[],alerts=[];
const vc=new VirtualConsole();vc.on("jsdomError",e=>errors.push(e.message));
const dom=new JSDOM(html,{url:"https://smartledger.test/",runScripts:"dangerously",pretendToBeVisual:true,virtualConsole:vc,beforeParse(w){
 w.matchMedia=()=>({matches:false,addEventListener(){}});
 w.alert=m=>alerts.push(String(m));w.confirm=()=>true;
 w.URL.createObjectURL=()=>"blob:test";w.URL.revokeObjectURL=()=>{};
 w.HTMLAnchorElement.prototype.click=function(){};
}});
const w=dom.window;
await new Promise(resolve=>w.document.readyState==="complete"?resolve():w.addEventListener("DOMContentLoaded",resolve,{once:true}));
w.eval(source);
assert.ok(w.document.querySelector('#nav [data-page="Units"]'),"Units is present in desktop navigation");
w.go("More");
assert.ok(w.document.querySelector("[data-units-link]"),"Units is accessible from mobile More tools");
w.go("Units");
assert.match(w.document.querySelector("#view").textContent,/Units & Conversions/,"dedicated unit manager renders");
w.slUnitForm();
w.document.querySelector("#sluName").value="carton";
w.document.querySelector("#sluGroup").value="Packaging";
w.document.querySelector("#sluBase").value="pcs";
w.document.querySelector("#sluFactor").value="24";
w.slSaveUnit({preventDefault(){}}, "");
assert.equal(w.eval('UNIT_CATALOG.find(x=>x.unit==="carton").group'),"count","packaging unit is mapped into transaction count group");
assert.equal(w.eval('UNIT_CATALOG.find(x=>x.unit==="carton").factor'),24,"custom pack conversion reaches the app unit catalogue");
assert.equal(w.eval('unitFactorForItem({unit:"carton",unitGroup:"count",baseUnit:"pcs",unitFactor:24},"pcs")'),1,"base-unit conversion factor is one");
w.itemForm();
assert.ok([...w.document.querySelectorAll("#iunit option")].some(x=>x.value==="carton"),"custom unit is selectable when creating an inventory item");
w.closeModal();
w.localStorage.setItem("sl_items",JSON.stringify([{id:1,name:"Cooking Oil Carton",code:"OIL24",qty:10,purchase:2400,price:120,wholesale:115,gst:0,unit:"carton",baseUnit:"pcs",unitFactor:24,unitGroup:"count",minStock:1}]));
w.localStorage.setItem("sl_suppliers",JSON.stringify([{name:"Supplier A",opening:0}]));
w.transactionForm("sales");
let item=w.document.querySelector(".txitem");item.value="0";w.txnRate(item);
let unit=w.document.querySelector(".txunit");assert.ok([...unit.options].some(x=>x.value==="pcs"),"sales unit picker offers pieces for a carton-stocked product");
unit.value="pcs";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),5,"sales rate converts from carton price to piece price");
w.document.querySelector(".txqty").value="12";w.updateTxnTotals();
let line=w.readTxnLines()[0];assert.equal(line.stockQty,0.5,"12 pieces converts to half a carton in stock units");
w.document.querySelector("#tinvoice").value="UNIT-SALE-1";w.document.querySelector("#tpaid").value="1440";
w.saveTransaction({preventDefault(){}}, "sales");
assert.equal(JSON.parse(w.localStorage.getItem("sl_items"))[0].qty,9.5,"sale deducts converted carton quantity");
w.transactionForm("purchases");
item=w.document.querySelector(".txitem");item.value="0";w.txnRate(item);
unit=w.document.querySelector(".txunit");unit.value="pcs";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),100,"purchase rate converts from carton cost to piece cost");
unit.value="carton";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),2400,"purchase rate returns to carton cost");
w.document.querySelector(".txqty").value="2";w.updateTxnTotals();
w.document.querySelector("#tparty").value="Supplier A";w.document.querySelector("#tinvoice").value="UNIT-PUR-1";w.document.querySelector("#tpaid").value="0";
w.saveTransaction({preventDefault(){}}, "purchases");
assert.equal(JSON.parse(w.localStorage.getItem("sl_items"))[0].qty,11.5,"purchase in cartons adds the correct primary stock quantity");
w.slUnitForm("carton");
w.document.querySelector("#sluFactor").value="12";w.slSaveUnit({preventDefault(){}}, "carton");
assert.equal(w.eval('UNIT_CATALOG.find(x=>x.unit==="carton").factor'),12,"editing a unit updates the conversion catalogue");
assert.equal(JSON.parse(w.localStorage.getItem("sl_items"))[0].unitFactor,12,"unit master updates linked products still using the previous master ratio");
w.slDeleteUnit("carton");
assert.match(alerts.at(-1),/assigned to 1 inventory item/,"deleting a unit used by inventory is blocked");
w.localStorage.setItem("sl_items","[]");w.slDeleteUnit("carton");
assert.equal(w.eval('UNIT_CATALOG.some(x=>x.unit==="carton")'),false,"deleting an unused custom unit removes it from the live catalogue");
assert.equal(errors.length,0,"no uncaught DOM runtime errors");
console.log("Units & conversions integration tests passed.");
dom.window.close();
