import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { JSDOM, VirtualConsole } from "jsdom";

const html=readFileSync("index.html","utf8")
 .replace(/<script src="[^"]+"><\/script>/g,"")
 .replace(/<script src='[^']+'><\/script>/g,"");
const source=readFileSync("units-conversions-v2.js","utf8");
const errors=[],alerts=[];
const vc=new VirtualConsole();vc.on("jsdomError",e=>errors.push(e.message));
const dom=new JSDOM(html,{url:"https://smartledger.test/",runScripts:"dangerously",pretendToBeVisual:true,virtualConsole:vc,beforeParse(w){
 w.matchMedia=()=>({matches:false,addEventListener(){}});
 w.alert=m=>alerts.push(String(m));w.confirm=()=>true;
 w.URL.createObjectURL=()=>"blob:test";w.URL.revokeObjectURL=()=>{};
 w.HTMLAnchorElement.prototype.click=function(){};
}});
const w=dom.window;
await new Promise(resolve=>w.document.readyState==="complete"?resolve():w.addEventListener("DOMContentLoaded",resolve,{once:true}));
w.eval(source);
assert.equal(w.eval("db.units"),"sl_units_master_v1","unit master remains in the account-scoped backup map");
assert.ok(w.document.querySelector('#nav [data-page="Units"]'),"Units is present in desktop navigation");
w.go("More");
assert.ok(w.document.querySelector("[data-units-link]"),"Units is accessible from mobile More tools");
w.go("Units");
assert.match(w.document.querySelector("#view").textContent,/Unit Master/,"Vyapar-style unit master renders");
assert.match(w.document.querySelector("#view").textContent,/Bulk Assign Units/,"bulk unit assignment is available");
w.slUnitForm();
w.document.querySelector("#sluName").value="carton";
w.document.querySelector("#sluGroup").value="count";
w.slSaveUnit({preventDefault(){}});
assert.ok(w.eval('UNIT_CATALOG.some(x=>x.unit==="carton"&&x.group==="count")'),"custom packaging unit is added to the selectable unit catalogue");
w.itemForm();
assert.ok([...w.document.querySelectorAll("#iunit option")].some(x=>x.value==="carton"),"custom unit is selectable as an item's base unit");
w.document.querySelector("#iunit").value="carton";
w.document.querySelector("#iunit").dispatchEvent(new w.Event("change",{bubbles:true}));
const secondary=w.document.querySelector("#isecondaryUnit");
assert.ok([...secondary.options].some(x=>x.value==="pcs"),"secondary unit picker offers pieces for quantity items");
secondary.value="pcs";secondary.dispatchEvent(new w.Event("change",{bubbles:true}));
w.document.querySelector("#iconversionRate").value="24";
assert.deepEqual(JSON.parse(JSON.stringify(w.readUnitFields("i"))),{unit:"carton",baseUnit:"pcs",unitFactor:1,unitGroup:"count",secondaryUnit:"pcs",conversionRate:24},"item-level base/secondary mapping stores 1 carton = 24 pieces");
w.closeModal();
w.localStorage.setItem("sl_items",JSON.stringify([{id:1,name:"Cooking Oil Carton",code:"OIL24",qty:10,purchase:2400,price:120,wholesale:115,gst:0,unit:"carton",baseUnit:"pcs",unitFactor:1,unitGroup:"count",secondaryUnit:"pcs",conversionRate:24,minStock:1}]));
w.localStorage.setItem("sl_suppliers",JSON.stringify([{name:"Supplier A",opening:0}]));
w.transactionForm("sales");
let item=w.document.querySelector(".txitem");item.value="0";w.txnRate(item);
let unit=w.document.querySelector(".txunit");
assert.deepEqual([...unit.options].map(x=>x.value),["carton","pcs"],"transaction unit picker offers only this item's base and secondary units");
unit.value="pcs";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),5,"sales rate converts from carton price to piece price");
w.document.querySelector(".txqty").value="12";w.updateTxnTotals();
assert.equal(w.readTxnLines()[0].stockQty,0.5,"12 pieces converts to half a carton in base stock");
w.document.querySelector("#tinvoice").value="UNIT-SALE-1";w.document.querySelector("#tpaid").value="60";
w.saveTransaction({preventDefault(){}}, "sales");
assert.equal(JSON.parse(w.localStorage.getItem("sl_items"))[0].qty,9.5,"sale deducts converted base quantity");
w.transactionForm("purchases");
item=w.document.querySelector(".txitem");item.value="0";w.txnRate(item);
unit=w.document.querySelector(".txunit");unit.value="pcs";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),100,"purchase rate converts from carton cost to piece cost");
unit.value="carton";unit.dispatchEvent(new w.Event("change",{bubbles:true}));
assert.equal(Number(w.document.querySelector(".txrate").value),2400,"purchase rate returns to carton cost");
w.document.querySelector(".txqty").value="2";w.updateTxnTotals();
w.document.querySelector("#tparty").value="Supplier A";w.document.querySelector("#tinvoice").value="UNIT-PUR-1";w.document.querySelector("#tpaid").value="0";
w.saveTransaction({preventDefault(){}}, "purchases");
assert.equal(JSON.parse(w.localStorage.getItem("sl_items"))[0].qty,11.5,"purchase in cartons adds the correct base stock quantity");
w.slUnitForm();w.document.querySelector("#sluName").value="tin";w.document.querySelector("#sluGroup").value="count";w.slSaveUnit({preventDefault(){}});
w.slBulkAssign();
assert.ok(w.document.querySelector(".slBulkItem"),"bulk assignment lists inventory items");
assert.equal(errors.length,0,"no uncaught DOM runtime errors");
console.log("Vyapar-style unit master and item-level conversion tests passed.");
dom.window.close();
