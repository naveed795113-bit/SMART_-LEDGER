import { readFileSync } from "node:fs";
import { JSDOM, VirtualConsole } from "jsdom";
import assert from "node:assert/strict";

const html=readFileSync("index.html","utf8").replace('<script src="./accounting.js"></script>','');
const accounting=readFileSync("accounting.js","utf8");
const errors=[],alerts=[];
const vc=new VirtualConsole();vc.on("jsdomError",e=>errors.push(e.message));
const dom=new JSDOM(html,{url:"https://smartledger.test/",runScripts:"dangerously",pretendToBeVisual:true,virtualConsole:vc,beforeParse(w){
  w.matchMedia=()=>({matches:false,addEventListener(){}});
  w.alert=m=>alerts.push(String(m));w.confirm=()=>true;
  w.URL.createObjectURL=()=>"blob:test";w.URL.revokeObjectURL=()=>{};
  w.HTMLAnchorElement.prototype.click=function(){};
}});
const {window:w}=dom;
w.eval(accounting);
w.go("Accounts");
assert.match(w.document.querySelector("#view").textContent,/Accounts & general ledger/);
assert.equal(JSON.parse(w.localStorage.getItem("sl_chart_accounts")).length,19);
w.newJournal();
w.document.querySelector("#jdate").value="2026-11-24";
w.document.querySelector("#jref").value="JV-TEST-001";
w.document.querySelector("#jnarration").value="Opening capital";
const rows=w.document.querySelectorAll("#journalLines tr");
rows[0].querySelector(".jaccount").value="1000";
rows[0].querySelector(".jdebit").value="100";
rows[1].querySelector(".jaccount").value="3000";
rows[1].querySelector(".jcredit").value="100";
w.postJournal({preventDefault(){}});
const entries=JSON.parse(w.localStorage.getItem("sl_account_journals"));
assert.equal(entries.length,1);
assert.equal(entries[0].lines.reduce((s,x)=>s+Number(x.debit),0),100);
assert.equal(entries[0].lines.reduce((s,x)=>s+Number(x.credit),0),100);
w.showTrialBalance();
assert.match(w.document.querySelector("#view").textContent,/Trial balance/);
assert.match(w.document.querySelector("#view").textContent,/Trial balance agrees/);
w.newJournal();
w.document.querySelector("#jdate").value="2026-11-24";
w.document.querySelector("#jref").value="JV-TEST-002";
w.document.querySelector("#jnarration").value="Unbalanced test";
const bad=w.document.querySelectorAll("#journalLines tr");
bad[0].querySelector(".jaccount").value="1000";
bad[0].querySelector(".jdebit").value="50";
bad[1].querySelector(".jaccount").value="3000";
bad[1].querySelector(".jcredit").value="40";
w.postJournal({preventDefault(){}});
assert.equal(JSON.parse(w.localStorage.getItem("sl_account_journals")).length,1);
assert.ok(alerts.some(x=>x.includes("not balanced")));
assert.equal(errors.length,0,"No runtime errors: "+errors.join("; "));
console.log("v18 accounting tests passed");
dom.window.close();
